export function getAppearance(id: AppearanceId): AppearanceConfig {
  return APPEARANCE_LIST.find((a) => a.id === id) ?? APPEARANCE_LIST[0];
}

export function loadSavedAppearanceId(): AppearanceId {
  try {
    const raw = localStorage.getItem(APPEARANCE_STORAGE_KEY) as AppearanceId | null;
    if (raw && APPEARANCE_LIST.some((a) => a.id === raw && a.available)) {
      return raw;
    }
  } catch {
    // Ignore private mode / storage errors
  }
  return 'midnight-glow';
}

export function saveAppearanceId(id: AppearanceId): void {
  try {
    localStorage.setItem(APPEARANCE_STORAGE_KEY, id);
  } catch {
    // Ignore storage errors
  }
}

export function createSceneConfigFromAppearance(
  appearance: AppearanceConfig,
  isLite: boolean
): SceneConfig {
  const d = appearance.defaults;
  return {
    appearanceId: appearance.id,
    bgColor: d.bgColor,
    accentColor: d.accentColor,
    particleCount: isLite ? d.particleCountLite : d.particleCountDesktop,
    particleColor1: d.particleColor1,
    particleColor2: d.particleColor2,
    boxCount: isLite ? d.boxCountLite : d.boxCountDesktop,
    bellCount: isLite ? d.bellCountLite : d.bellCountDesktop,
    boxColor1: d.boxColor1,
    boxColor2: d.boxColor2,
    ribbonColor: d.ribbonColor,
    bellColor: d.bellColor,
    garlandColors: d.garlandColors,
    snowGroundColor: appearance.space.groundMidColor,
    ringColor: appearance.space.groundCoreColor,
    starColor: d.starColor,
  };
}
